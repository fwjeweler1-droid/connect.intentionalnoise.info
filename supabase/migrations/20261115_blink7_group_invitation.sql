create table if not exists public.connect_invitation_campaigns (
  code text primary key check (code ~ '^[A-Z0-9_-]{4,40}$'),
  validation_source text not null check (char_length(validation_source) between 3 and 80),
  organizer text not null,
  seat_limit integer check (seat_limit between 1 and 500),
  enabled boolean not null default false,
  roster_confirmed_at timestamptz,
  created_at timestamptz not null default now(),
  check (enabled = false or (seat_limit is not null and roster_confirmed_at is not null))
);

create table if not exists public.connect_invitation_roster (
  id uuid primary key default gen_random_uuid(),
  campaign_code text not null references public.connect_invitation_campaigns(code),
  listed_name text not null check (char_length(btrim(listed_name)) between 1 and 100),
  match_key text generated always as
    (lower(regexp_replace(btrim(listed_name), '[[:space:]]+', ' ', 'g'))) stored,
  participant_role text not null check (participant_role in ('musician','sound_engineer','other_production')),
  claimed_by uuid unique references auth.users(id) on delete set null,
  claimed_at timestamptz,
  created_at timestamptz not null default now(),
  unique (campaign_code, match_key)
);

create table if not exists public.connect_invitation_redemptions (
  id uuid primary key default gen_random_uuid(),
  campaign_code text not null references public.connect_invitation_campaigns(code),
  roster_id uuid not null unique references public.connect_invitation_roster(id),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  validation_source text not null,
  waived_fee_cents integer not null default 1200 check (waived_fee_cents=1200),
  redeemed_at timestamptz not null default now()
);

create table if not exists public.connect_invitation_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  attempted_at timestamptz not null default now()
);
create index if not exists connect_invitation_attempts_user_time_idx
 on public.connect_invitation_attempts(user_id,attempted_at desc);
create index if not exists connect_invitation_roster_campaign_idx
 on public.connect_invitation_roster(campaign_code);

alter table public.connect_invitation_campaigns enable row level security;
alter table public.connect_invitation_roster enable row level security;
alter table public.connect_invitation_redemptions enable row level security;
alter table public.connect_invitation_attempts enable row level security;

