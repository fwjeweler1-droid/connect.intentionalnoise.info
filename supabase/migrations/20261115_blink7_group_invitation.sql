create or replace function public.redeem_connect_invitation(p_code text,p_name text)
returns jsonb language plpgsql security definer set search_path=''
as $func$
declare
  v_user uuid := (select auth.uid());
  v_code text := upper(btrim(coalesce(p_code,'')));
  v_name text := lower(regexp_replace(btrim(coalesce(p_name,'')),'[[:space:]]+',' ','g'));
  v_campaign public.connect_invitation_campaigns%rowtype;
  v_roster public.connect_invitation_roster%rowtype;
  v_redemption uuid;
  v_features jsonb;
  v_studio jsonb;
begin
  if v_user is null then raise exception 'Sign in required'; end if;
  if not exists (select 1 from auth.users where id=v_user and email_confirmed_at is not null)
    then raise exception 'Confirm your account email first'; end if;
  if char_length(v_code) not between 4 and 40 or char_length(v_name) not between 1 and 100
    then raise exception 'Enter an invitation code and the name listed on the invitation'; end if;

  -- A shared group code is intentionally NOT an unrestricted public coupon.
  -- Serialize per user and allow only a small number of guesses per 24 hours.
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(v_user::text,761225));
  if (select count(*) from public.connect_invitation_attempts
      where user_id=v_user and attempted_at>now()-interval '24 hours') >= 12 then
    raise exception 'Too many attempts. Contact Intentional Noise for assistance';
  end if;
  insert into public.connect_invitation_attempts(user_id) values(v_user);

  if exists(select 1 from public.connect_account_price_locks where user_id=v_user)
    then return jsonb_build_object('status','already_locked'); end if;
  if exists(select 1 from public.artist_verification_payments where user_id=v_user)
    then return jsonb_build_object('status','payment_review','message','An existing payment needs review before a complimentary pass can be issued'); end if;

  select * into v_campaign from public.connect_invitation_campaigns
   where code=v_code for update;
  if not found or v_campaign.enabled is distinct from true or
       v_campaign.seat_limit is null or v_campaign.roster_confirmed_at is null
    then return jsonb_build_object('status','invalid','message','Invitation not active or roster name not matched'); end if;
  if (select count(*) from public.connect_invitation_roster where campaign_code=v_code)
       <> v_campaign.seat_limit then
    return jsonb_build_object('status','invalid','message','Invitation not active or roster name not matched'); end if;
  select * into v_roster from public.connect_invitation_roster
    where campaign_code=v_code and match_key=v_name for update;
  if not found or v_roster.claimed_at is not null then
    return jsonb_build_object('status','invalid','message','Invitation not active or roster name not matched'); end if;

  update public.connect_invitation_roster
    set claimed_by=v_user,claimed_at=now()
    where id=v_roster.id and claimed_by is null and claimed_at is null;
  if not found then raise exception 'Invitation has already been claimed'; end if;

  insert into public.connect_invitation_redemptions
    (campaign_code,roster_id,user_id,validation_source)
  values (v_code,v_roster.id,v_user,v_campaign.validation_source)
  returning id into v_redemption;

  insert into public.verified_artist_accounts(user_id,request_id,verification_basis)
   values(v_user,null,'owner_approval') on conflict(user_id) do nothing;

  select coalesce(jsonb_agg(jsonb_build_object('feature',feature_key,
    'expires_at',expires_at)),'[]'::jsonb) into v_features
    from public.connect_member_entitlements
    where user_id=v_user and is_enabled and (expires_at is null or expires_at>now());
  select coalesce(jsonb_agg(jsonb_build_object('project_id',project_id,'role',role)),
    '[]'::jsonb) into v_studio
    from public.studio_members where user_id=v_user;

  insert into public.connect_account_price_locks
    (user_id,invitation_redemption_id,locked_features)
  values(v_user,v_redemption,jsonb_build_object(
    'version','2026-11-14-current-free-benefits',
    'promise','Current included account features remain free if base pricing changes; no recurring verification charge',
    'source',v_campaign.validation_source,
    'waived_fee_cents',1200,
    'features',jsonb_build_array(
      'free_account_and_private_profile','member_directory_search',
      'profile_visibility_controls','up_to_five_60_second_media_previews',
      'one_preferred_storage_provider','member_resources',
      'current_gig_request_access','eligible_owner_approved_public_artist_showcase'),
    'studio_access_at_redemption',v_studio,
    'already_enabled_entitlements',v_features,
    'excludes',jsonb_build_array(
      'new_optional_paid_features','new_merchant_websites',
      'future_storage_addons','third_party_provider_fees')
  ));
  return jsonb_build_object('status','redeemed','validation_source',v_campaign.validation_source);
end
$func$;
revoke all on function public.redeem_connect_invitation(text,text) from public,anon;
grant execute on function public.redeem_connect_invitation(text,text) to authenticated;

